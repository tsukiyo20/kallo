//! Collects the `.kalofilm` and `.kalopaper` files in this crate into two byte
//! tables that `lib.rs` includes.
//!
//! The files are copies of the repository's `data/` directory, made by
//! `just sync-data`. This script deliberately does not look at that directory:
//! the copy in the crate must be enough on its own, and the test in `src/lib.rs`
//! compares it with the originals when the repository is present.

use std::env;
use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};

fn main() {
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let data = manifest.join("data");

    let films = films(&data.join("films"));
    let papers = papers(&data.join("papers"));
    assert!(
        !films.is_empty(),
        "no `.kalofilm` files under {} — the crate is only its data",
        data.display()
    );

    let mut code = String::new();
    code.push_str("// @generated by build.rs from `data/`. Do not edit.\n\n");
    code.push_str("/// Every film file in this crate, by stock id.\n");
    code.push_str("pub static FILMS: &[Source] = &[\n");
    emit(&mut code, &manifest, &films);
    code.push_str("];\n\n");
    code.push_str("/// Every paper file in this crate, by stock id.\n");
    code.push_str("pub static PAPERS: &[Source] = &[\n");
    emit(&mut code, &manifest, &papers);
    code.push_str("];\n");

    let out = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR")).join("sources.rs");
    fs::write(&out, code).expect("write the source table");

    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed=data");
}

/// The `.kalofilm` files, as `(stock id, path)` pairs in id order.
fn films(directory: &Path) -> Vec<(String, PathBuf)> {
    let mut found = Vec::new();
    let entries = fs::read_dir(directory).unwrap_or_else(|error| {
        panic!("{}: {error}", directory.display());
    });
    for entry in entries.flatten() {
        let directory = entry.path();
        if !directory.is_dir() {
            continue;
        }
        let Some(name) = directory
            .file_name()
            .map(|name| name.to_string_lossy().to_string())
        else {
            continue;
        };
        let file = directory.join(format!("{name}.kalofilm"));
        if file.is_file() {
            found.push((name, file));
        }
    }
    found.sort();
    found
}

/// The `.kalopaper` files, as `(stock id, path)` pairs in id order.
fn papers(directory: &Path) -> Vec<(String, PathBuf)> {
    let mut found = Vec::new();
    let Ok(entries) = fs::read_dir(directory) else {
        return found;
    };
    for entry in entries.flatten() {
        let path = entry.path();
        let is_paper = path
            .extension()
            .is_some_and(|extension| extension == "kalopaper");
        if !is_paper {
            continue;
        }
        let Some(name) = path
            .file_stem()
            .map(|name| name.to_string_lossy().to_string())
        else {
            continue;
        };
        found.push((name, path));
    }
    found.sort();
    found
}

/// Writes one `Source { … }` literal per file, the bytes included at compile time.
fn emit(code: &mut String, manifest: &Path, files: &[(String, PathBuf)]) {
    for (name, path) in files {
        let relative = path
            .strip_prefix(manifest)
            .unwrap_or_else(|_| panic!("{} is outside the crate", path.display()));
        let relative = relative.to_string_lossy().replace('\\', "/");
        writeln!(code, "    Source {{").unwrap();
        writeln!(code, "        name: {name:?},").unwrap();
        writeln!(
            code,
            "        bytes: include_bytes!(concat!(env!(\"CARGO_MANIFEST_DIR\"), \"/{relative}\")),"
        )
        .unwrap();
        writeln!(code, "    }},").unwrap();
    }
}
